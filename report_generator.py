
import io
import pandas as pd

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    Image,
)


def create_pdf_report(
    results: pd.DataFrame,
    extracted_text: str,
    chart_png: bytes,
    generated_at: str
) -> bytes:

    output = io.BytesIO()

    document = SimpleDocTemplate(
        output,
        pagesize=A4,
        rightMargin=15 * mm,
        leftMargin=15 * mm,
        topMargin=16 * mm,
        bottomMargin=16 * mm,
        title="Medical Report Summary"
    )

    styles = getSampleStyleSheet()

    styles.add(
        ParagraphStyle(
            name="BrandTitle",
            parent=styles["Title"],
            textColor=colors.HexColor("#12304A"),
            fontSize=21,
            leading=25
        )
    )

    styles.add(
        ParagraphStyle(
            name="SmallNote",
            parent=styles["BodyText"],
            textColor=colors.HexColor("#586b80"),
            fontSize=8,
            leading=11
        )
    )

    story = [
        Paragraph("MediLens", styles["BrandTitle"]),
        Paragraph(
            "Medical Laboratory Report Summary",
            styles["Heading2"]
        ),
        Paragraph(
            f"Generated: {generated_at}",
            styles["SmallNote"]
        ),
        Spacer(1, 7 * mm),
        Paragraph("Detected Results", styles["Heading2"]),
        Paragraph(
            "Automated extraction may be incomplete or incorrect. "
            "Verify values against the original PDF.",
            styles["SmallNote"]
        ),
        Spacer(1, 3 * mm)
    ]

    table_data = [[
        "Test",
        "Value",
        "Reference Range",
        "Status"
    ]]

    for _, row in results.iterrows():
        table_data.append([
            str(row.get("Test", "")),
            str(row.get("Value", "")),
            str(row.get("Reference range", "")),
            str(row.get("Status", "Not assessed"))
        ])

    results_table = Table(
        table_data,
        repeatRows=1,
        colWidths=[
            34 * mm,
            22 * mm,
            48 * mm,
            45 * mm
        ]
    )

    results_table.setStyle(
        TableStyle([
            (
                "BACKGROUND",
                (0, 0),
                (-1, 0),
                colors.HexColor("#12304A")
            ),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, -1), 8),
            ("GRID", (0, 0), (-1, -1), 0.35, colors.HexColor("#d8e1ea")),
            (
                "ROWBACKGROUNDS",
                (0, 1),
                (-1, -1),
                [colors.white, colors.HexColor("#f4f8fb")]
            ),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("LEFTPADDING", (0, 0), (-1, -1), 5),
            ("RIGHTPADDING", (0, 0), (-1, -1), 5),
            ("TOPPADDING", (0, 0), (-1, -1), 5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ])
    )

    story.append(results_table)

    if chart_png:
        story.extend([
            Spacer(1, 7 * mm),
            Paragraph("Result Status Overview", styles["Heading2"]),
            Spacer(1, 2 * mm),
            Image(
                io.BytesIO(chart_png),
                width=165 * mm,
                height=73 * mm
            )
        ])

    story.extend([
        Spacer(1, 7 * mm),
        Paragraph("Important Medical Notice", styles["Heading2"]),
        Paragraph(
            "This document is an educational summary generated by software. "
            "It is not a diagnosis or treatment plan and is not a substitute "
            "for advice from a qualified healthcare professional. "
            "Reference ranges vary by laboratory and patient factors. "
            "Results marked Not assessed were not classified by this application.",
            styles["SmallNote"]
        )
    ])

    document.build(story)

    return output.getvalue()
